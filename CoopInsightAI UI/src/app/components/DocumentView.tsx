import { ShieldCheck } from "lucide-react";
import { BrandLockup } from "./BrandMark";

/**
 * A stored report, shown on screen the way the PDF prints it: the mark, the
 * issuing body, the title, a details panel (covers, period, generated on and
 * by, reference, verification code), the headline tiles, the sections, and the
 * note on how to check it. One layout, so what someone reads on screen is
 * recognisably the document they will be handed.
 */

export interface ReportSection {
  title: string;
  note?: string;
  paragraphs?: string[];
  facts?: Array<{ label: string; value: string }>;
  columns?: string[];
  rows?: Array<Array<string | number | null>>;
  totals?: Array<string | number | null>;
}

export interface ReportContent {
  title: string;
  type: string;
  cooperativeName: string | null;
  cooperative?: { name: string; lines: string[] } | null;
  periodFrom: string | null;
  periodTo: string | null;
  generatedAt: string;
  preparedBy?: string | null;
  preparedByRole?: string | null;
  scopeLabel?: string | null;
  narrative?: string[];
  summary: Array<{ label: string; value: string }>;
  sections: ReportSection[];
  signatories?: string[];
}

export interface DocumentInfo {
  reference: string;
  verificationCode: string;
  issuedAt: string;
  issuedBy?: string | null;
  issuedByRole?: string | null;
  scopeLabel?: string | null;
  period?: string | null;
}

export const longDate = (v: string | null | undefined) =>
  v ? new Date(v).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" }) : "—";

export const dateTime = (v: string | null | undefined) =>
  v
    ? new Date(v).toLocaleString("en-GB", { day: "numeric", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" })
    : "—";

const isFigure = (v: unknown) => typeof v === "number" || /^(RWF\s*)?[-+]?\d[\d,]*(\.\d+)?\s*%?$/.test(String(v ?? "").trim());

export function DocumentView({ content, document }: { content: ReportContent; document?: DocumentInfo | null }) {
  const period =
    content.periodFrom && content.periodTo
      ? `${longDate(content.periodFrom)} to ${longDate(content.periodTo)}`
      : `Position as at ${longDate(content.generatedAt)}`;
  const org = content.cooperative ?? (content.cooperativeName ? { name: content.cooperativeName, lines: [] } : null);

  const details: Array<[string, string, boolean?]> = [
    ["Covers", document?.scopeLabel ?? content.scopeLabel ?? content.cooperativeName ?? "—"],
    ["Period", period],
    ["Generated on", dateTime(document?.issuedAt ?? content.generatedAt)],
    ["Generated by", [document?.issuedBy ?? content.preparedBy, document?.issuedByRole ?? content.preparedByRole].filter(Boolean).join(", ") || "—"],
    ...(document
      ? ([["Reference", document.reference, true], ["Verification code", document.verificationCode, true]] as Array<[string, string, boolean]>)
      : []),
  ];

  return (
    <article className="space-y-6 text-gray-900">
      {/* Brand band */}
      <header className="border-b-2 border-[#2D6A4F] pb-4">
        <div className="flex flex-wrap items-start justify-between gap-4">
          <BrandLockup subtitle="Cooperative management and oversight platform · Gasabo District, Rwanda" />
          {document && (
            <div className="text-right">
              <p className="text-[10px] uppercase tracking-wider text-gray-500">Document reference</p>
              <p className="font-mono text-sm font-bold">{document.reference}</p>
              <p className="text-xs text-gray-500">Issued {dateTime(document.issuedAt)}</p>
            </div>
          )}
        </div>
      </header>

      <div>
        {org && (
          <>
            <p className="font-semibold text-[#2D6A4F]">{org.name}</p>
            {org.lines?.length ? <p className="text-xs text-gray-500">{org.lines.join("  ·  ")}</p> : null}
          </>
        )}
        <h2 className="mt-3 text-2xl font-bold">{content.title}</h2>
        <p className="text-sm text-gray-500">{content.periodFrom ? `For the period ${period}` : period}</p>
      </div>

      {/* Document details */}
      <dl className="grid gap-x-8 gap-y-2 rounded-xl border-l-4 border-[#2D6A4F] bg-[#EEF5F1] p-4 text-sm sm:grid-cols-2">
        {details.map(([k, v, mono]) => (
          <div key={k} className="flex gap-3">
            <dt className="w-32 flex-shrink-0 text-xs uppercase tracking-wide text-gray-500 pt-0.5">{k}</dt>
            <dd className={`font-semibold ${mono ? "font-mono" : ""}`}>{v}</dd>
          </div>
        ))}
      </dl>

      {(content.narrative ?? []).map((p, i) => (
        <p key={i} className="text-sm leading-relaxed text-gray-800">{p}</p>
      ))}

      {content.summary.length > 0 && (
        <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
          {content.summary.map((item) => (
            <div key={item.label} className="rounded-lg border-l-[3px] border-[#D4A574] bg-gray-50 px-4 py-3">
              <p className="text-[11px] uppercase tracking-wide text-gray-500">{item.label}</p>
              <p className="mt-1 text-lg font-bold text-[#1B4332]">{item.value}</p>
            </div>
          ))}
        </div>
      )}

      {content.sections.map((section) => (
        <section key={section.title}>
          <h3 className="flex items-center gap-2 font-semibold text-[#1B4332]">
            <span className="h-4 w-1 rounded bg-[#D4A574]" />
            {section.title}
          </h3>
          {section.note && <p className="ml-3 text-xs text-gray-500">{section.note}</p>}
          {(section.paragraphs ?? []).map((p, i) => (
            <p key={i} className="mt-2 text-sm leading-relaxed text-gray-800">{p}</p>
          ))}
          {section.facts && section.facts.length > 0 && (
            <dl className="mt-2 grid gap-x-8 text-sm sm:grid-cols-2">
              {section.facts.map((f) => (
                <div key={f.label} className="flex justify-between gap-4 border-b border-gray-100 py-1.5">
                  <dt className="text-gray-500">{f.label}</dt>
                  <dd className="text-right font-semibold">{f.value}</dd>
                </div>
              ))}
            </dl>
          )}
          {section.columns && section.columns.length > 0 && (
            <div className="mt-2 max-h-[26rem] overflow-auto rounded-lg border border-gray-200">
              <table className="w-full text-sm">
                <thead className="sticky top-0 bg-[#2D6A4F] text-white">
                  <tr>
                    {section.columns.map((c, i) => (
                      <th key={i} className="whitespace-nowrap px-3 py-2 text-left text-xs font-semibold">{c}</th>
                    ))}
                  </tr>
                </thead>
                <tbody className="divide-y divide-gray-100">
                  {(section.rows ?? []).length === 0 ? (
                    <tr>
                      <td colSpan={section.columns.length} className="px-3 py-4 text-center text-gray-500">
                        Nothing recorded for this period.
                      </td>
                    </tr>
                  ) : (
                    (section.rows ?? []).map((row, i) => (
                      <tr key={i} className={i % 2 ? "bg-gray-50" : ""}>
                        {row.map((cell, j) => (
                          <td key={j} className={`px-3 py-1.5 text-gray-800 ${isFigure(cell) ? "text-right tabular-nums" : ""}`}>{cell}</td>
                        ))}
                      </tr>
                    ))
                  )}
                  {section.totals && (
                    <tr className="border-t-2 border-[#1B4332] bg-[#EEF5F1] font-semibold">
                      {section.totals.map((cell, j) => (
                        <td key={j} className={`px-3 py-2 ${isFigure(cell) ? "text-right tabular-nums" : ""}`}>{cell}</td>
                      ))}
                    </tr>
                  )}
                </tbody>
              </table>
            </div>
          )}
        </section>
      ))}

      {document && (
        <aside className="flex items-start gap-3 rounded-xl border border-[#2D6A4F] p-4 text-sm">
          <ShieldCheck className="mt-0.5 h-5 w-5 flex-shrink-0 text-[#2D6A4F]" />
          <p className="text-gray-700">
            <span className="font-semibold text-[#1B4332]">Authenticity. </span>
            Entered in the document register as <span className="font-mono">{document.reference}</span>. Anyone handed
            this report can confirm it at <span className="font-medium">/verify</span> with the code{" "}
            <span className="font-mono font-semibold">{document.verificationCode}</span>.
            {content.signatories?.length ? ` The PDF carries signature lines for ${content.signatories.join(", ")}.` : ""}
          </p>
        </aside>
      )}
    </article>
  );
}
