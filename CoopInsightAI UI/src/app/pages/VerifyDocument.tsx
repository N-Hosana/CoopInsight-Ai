import { useEffect, useState } from "react";
import { useNavigate, useParams, Link } from "react-router";
import { ShieldCheck, ShieldAlert, Search } from "lucide-react";
import { BrandLockup } from "../components/BrandMark";

/**
 * /verify and /verify/:code — open to anyone, no account needed.
 *
 * The person checking a report is usually not a user of the system: a bank
 * officer, a funder, an auditor handed a printout. They type the code printed
 * at the foot of every page and see what the register says was issued — the
 * title, who it covers, the period, who generated it and when. If what they
 * hold disagrees with that, it is not the document that was issued.
 */

const BASE_URL = import.meta.env.VITE_API_URL || "http://localhost:5000/api";

interface Result {
  valid: boolean;
  message: string;
  data?: {
    reference: string;
    title: string;
    kind: string;
    covers: string | null;
    periodFrom: string | null;
    periodTo: string | null;
    issuedBy: string | null;
    issuedByRole: string | null;
    issuedAt: string;
    fingerprint: string | null;
  };
}

const longDay = (v: string | null) =>
  v ? new Date(`${v.slice(0, 10)}T12:00:00`).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" }) : null;

export function VerifyDocument() {
  const { code: initial } = useParams();
  const navigate = useNavigate();
  const [code, setCode] = useState(initial ?? "");
  const [result, setResult] = useState<Result | null>(null);
  const [loading, setLoading] = useState(false);

  useEffect(() => {
    if (!initial) return;
    setLoading(true);
    setResult(null);
    fetch(`${BASE_URL}/documents/verify/${encodeURIComponent(initial)}`)
      .then(async (r) => setResult(await r.json()))
      .catch(() => setResult({ valid: false, message: "The verification service could not be reached. Try again shortly." }))
      .finally(() => setLoading(false));
  }, [initial]);

  const submit = (e: React.FormEvent) => {
    e.preventDefault();
    const c = code.trim().toUpperCase();
    if (c) navigate(`/verify/${encodeURIComponent(c)}`);
  };

  const d = result?.data;
  const period = d && (d.periodFrom || d.periodTo) ? [longDay(d.periodFrom), longDay(d.periodTo)].filter(Boolean).join(" to ") : null;

  return (
    <div className="min-h-screen bg-[#F5F1E8] px-4 py-10">
      <div className="mx-auto max-w-xl space-y-6">
        <BrandLockup subtitle="Document verification" />

        <div className="rounded-2xl border border-gray-200 bg-white p-6 shadow-sm">
          <h1 className="text-xl font-bold text-gray-900">Check a document</h1>
          <p className="mt-1 text-sm text-gray-600">
            Every report and certificate issued by CoopInsightAI carries a verification code at the foot of each page.
            Enter it to see what was issued.
          </p>
          <form onSubmit={submit} className="mt-4 flex gap-2">
            <input
              value={code}
              onChange={(e) => setCode(e.target.value.toUpperCase())}
              placeholder="e.g. YNW8-SJQH"
              className="flex-1 rounded-lg border border-gray-300 px-4 py-2.5 font-mono tracking-wider focus:outline-none focus:ring-2 focus:ring-[#2D6A4F]"
              autoFocus={!initial}
            />
            <button className="flex items-center gap-2 rounded-lg bg-[#2D6A4F] px-4 py-2.5 font-medium text-white hover:bg-[#1B4332]">
              <Search className="h-4 w-4" /> Check
            </button>
          </form>
        </div>

        {loading && <p className="text-center text-sm text-gray-500">Checking…</p>}

        {result && (
          <div className={`rounded-2xl border-2 bg-white p-6 shadow-sm ${result.valid ? "border-[#2D6A4F]" : "border-red-300"}`}>
            <div className="flex items-start gap-3">
              {result.valid ? (
                <ShieldCheck className="h-8 w-8 flex-shrink-0 text-[#2D6A4F]" />
              ) : (
                <ShieldAlert className="h-8 w-8 flex-shrink-0 text-red-600" />
              )}
              <div>
                <p className={`text-lg font-bold ${result.valid ? "text-[#1B4332]" : "text-red-700"}`}>
                  {result.valid ? "Genuine document" : d ? "Withdrawn" : "Not found"}
                </p>
                <p className="text-sm text-gray-600">{result.message}</p>
              </div>
            </div>

            {d && (
              <dl className="mt-5 divide-y divide-gray-100 text-sm">
                {[
                  ["Title", d.title],
                  ["Reference", d.reference],
                  ["Covers", d.covers],
                  ["Period", period],
                  ["Generated by", [d.issuedBy, d.issuedByRole].filter(Boolean).join(", ") || null],
                  ["Generated on", new Date(d.issuedAt).toLocaleString("en-GB", { dateStyle: "long", timeStyle: "short" })],
                  ["Fingerprint", d.fingerprint ? `${d.fingerprint.slice(0, 16)}…${d.fingerprint.slice(-8)}` : null],
                ]
                  .filter(([, v]) => v)
                  .map(([k, v]) => (
                    <div key={k as string} className="flex gap-4 py-2">
                      <dt className="w-28 flex-shrink-0 text-gray-500">{k}</dt>
                      <dd className={`font-medium text-gray-900 ${k === "Reference" || k === "Fingerprint" ? "font-mono text-xs leading-5" : ""}`}>{v}</dd>
                    </div>
                  ))}
              </dl>
            )}

            {d && result.valid && (
              <p className="mt-4 rounded-lg bg-[#EEF5F1] px-3 py-2 text-xs text-gray-700">
                Compare these details with the document you hold. If the title, the cooperative, the period or the date
                differ, the document is not the one that was issued.
              </p>
            )}
          </div>
        )}

        <p className="text-center text-xs text-gray-500">
          <Link to="/login" className="hover:underline">Sign in to CoopInsightAI</Link>
        </p>
      </div>
    </div>
  );
}
